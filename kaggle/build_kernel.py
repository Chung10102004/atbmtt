"""Bundle src/ + run_experiments.py into one Kaggle kernel script, then push it with the Kaggle CLI.

    python kaggle/build_kernel.py --args "--exps E0 E1 E2 --seeds 0 1 2"
    kaggle kernels push -p kaggle/kernel
    kaggle kernels status hoangducchung/aml-baseline-e0-e2
    kaggle kernels output hoangducchung/aml-baseline-e0-e2 -p results/kaggle
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(__file__).parent / "kernel"
SLUG = "aml-baseline-e0-e2"
DATASET = "ealtman2019/ibm-transactions-for-anti-money-laundering-aml"

TEMPLATE = '''# Auto-generated by kaggle/build_kernel.py - do not edit by hand.
import os, shutil, subprocess, sys
from pathlib import Path

subprocess.run([sys.executable, "-m", "pip", "install", "-q", "ctgan"], check=True)

WORK = Path("/kaggle/working")
FILES = {files!r}
for rel, code in FILES.items():
    p = WORK / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(code)

csv = next(Path("/kaggle/input").rglob("HI-Small_Trans.csv"))
env = dict(os.environ, AML_RAW_CSV=str(csv),
           AML_DEVICE="cuda" if Path("/dev/nvidia0").exists() else "cpu")
try:
    subprocess.run([sys.executable, str(WORK / "run_experiments.py"), *{args!r}],
                   check=True, cwd=WORK, env=env)
finally:
    shutil.rmtree(WORK / "data", ignore_errors=True)  # do not keep features.parquet in the output
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--args", default="--exps E0 E1 E2 --seeds 0 1 2 --ratio 1.0")
    ap.add_argument("--cpu", action="store_true", help="do not request a GPU")
    a = ap.parse_args()

    # Only code + LLM data that is already generated (E3). Do NOT bundle llm_config.py (contains the API key).
    files = {str(p.relative_to(ROOT)): p.read_text()
             for p in [*sorted((ROOT / "src").glob("*.py")), ROOT / "run_experiments.py",
                       *sorted((ROOT / "data/llm").glob("llm_seed*.csv"))]}
    OUT.mkdir(exist_ok=True)
    (OUT / "kernel.py").write_text(TEMPLATE.format(files=files, args=a.args.split()))
    meta = {
        "id": f"hoangducchung/{SLUG}",
        "title": SLUG,
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": not a.cpu,
        "enable_internet": True,
        "dataset_sources": [DATASET],
        "competition_sources": [],
        "kernel_sources": [],
    }
    (OUT / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"Built {OUT}/kernel.py with args: {a.args}")


if __name__ == "__main__":
    main()
