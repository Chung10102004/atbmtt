"""Build a private Kaggle GPU script with an explicit code/data allowlist."""
import argparse
import json
import re
import shlex
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATASET = "ealtman2019/ibm-transactions-for-anti-money-laundering-aml"
DEPENDENCIES = ["numpy==2.2.6", "pandas==2.3.3", "scikit-learn==1.7.2",
                "imbalanced-learn==0.14.0", "xgboost==3.1.1", "ctgan==0.11.0",
                "pyarrow==21.0.0", "tabulate==0.9.0"]

TEMPLATE = '''# Generated by kaggle/build_kernel.py. Credentials are never bundled.
import os, subprocess, sys
from pathlib import Path

subprocess.run([sys.executable, "-m", "pip", "install", "-q", *{dependencies!r}], check=True)
WORK = Path("/kaggle/working")
FILES = {files!r}
for rel, contents in FILES.items():
    p = WORK / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(contents, encoding="utf-8")
csv = next(Path("/kaggle/input").rglob("HI-Small_Trans.csv"))
gpu = subprocess.run(["nvidia-smi", "-L"], capture_output=True, text=True)
print(gpu.stdout, flush=True)
if gpu.returncode:
    raise RuntimeError("GPU requested but unavailable; refusing an unintended CPU run")
env = dict(os.environ, AML_RAW_CSV=str(csv), AML_DEVICE="cuda", PYTHONUNBUFFERED="1")
subprocess.run([sys.executable, "-B", "-m", "unittest", "discover", "-s", "tests", "-v"],
               cwd=WORK, env=env, check=True)
subprocess.run([sys.executable, "-B", str(WORK / "run_experiments.py"), *{args!r}],
               cwd=WORK, env=env, check=True)
'''


def bundle_files(llm_dir=None):
    names = ["src/data.py", "src/augment.py", "src/model.py", "src/llm_gen.py", "src/llm_validate.py",
             "run_experiments.py", "tests/test_data.py", "tests/test_experiments.py"]
    files = {name: (ROOT / name).read_text(encoding="utf-8") for name in names}
    if llm_dir is not None:
        directory = Path(llm_dir).resolve()
        if not directory.is_relative_to((ROOT / "data/llm").resolve()):
            raise ValueError("LLM directory must be inside data/llm")
        paths = [*directory.glob("llm_seed*.csv"), *directory.glob("llm_seed*_meta.json")]
        for variant in ("basic", "aml"):
            paths.extend((directory / variant).glob("llm_seed*.csv"))
            paths.extend((directory / variant).glob("llm_seed*_meta.json"))
        if not paths:
            raise ValueError("No LLM cache files in the requested directory")
        for p in paths:
            files[p.relative_to(ROOT).as_posix()] = p.read_text(encoding="utf-8")
    return files


def build(owner, slug, args, llm_dir=None):
    if not re.fullmatch(r"[A-Za-z0-9_-]+", owner) or not re.fullmatch(r"[a-z0-9-]+", slug):
        raise ValueError("Invalid Kaggle owner or kernel slug")
    source = TEMPLATE.format(dependencies=DEPENDENCIES, files=bundle_files(llm_dir), args=args)
    compile(source, "kernel.py", "exec")
    meta = {"id": f"{owner}/{slug}", "title": slug, "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_internet": True, "dataset_sources": [DATASET],
            "competition_sources": [], "kernel_sources": []}
    return source, meta


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--owner", required=True)
    ap.add_argument("--slug", default="aml-rerun-20261029")
    ap.add_argument("--output-dir", type=Path, default=ROOT / "kaggle/kernel")
    ap.add_argument("--args", default="--exps E0 ER E1 E2 --seeds 0 1 2 --ratio 0.5 --rebuild-features")
    ap.add_argument("--llm-dir", type=Path)
    args = ap.parse_args()
    source, meta = build(args.owner, args.slug, shlex.split(args.args), llm_dir=args.llm_dir)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "kernel.py").write_text(source, encoding="utf-8")
    (args.output_dir / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"Built {meta['id']}: {args.output_dir}")


if __name__ == "__main__":
    main()
